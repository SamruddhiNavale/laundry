async def reminder_worker():
    while True:
        try:
            await asyncio.to_thread(send_due_reminders)
        except Exception:
            logger.exception('Laundry reminder worker failed')
        await asyncio.sleep(15)


@asynccontextmanager
async def lifespan(app):
    worker = None if os.environ.get('VERCEL') else asyncio.create_task(reminder_worker())
    try:
        yield
    finally:
        if worker:
            worker.cancel()
            try:
                await worker
            except asyncio.CancelledError:
                pass


app = FastAPI(title='Loop Laundry API', lifespan=lifespan)


@app.middleware('http')
async def response_headers(request, call_next):
    response = await call_next(request)
    response.headers['X-Content-Type-Options'] = 'nosniff'
    response.headers['Referrer-Policy'] = 'same-origin'
    if request.url.path.startswith('/api/'):
        response.headers['Cache-Control'] = 'no-store'
    return response


@app.exception_handler(RequestValidationError)
async def validation_error(request, exc):
    # Keep credential inputs and request bodies out of validation responses.
    errors = [{key: error[key] for key in ('loc', 'msg', 'type')} for error in exc.errors()]
    return JSONResponse(status_code=422, content={'detail': errors})


class PostgresConnection:
    """Small compatibility layer for the app's parameterized SQLite queries."""
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row
        self.connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)

    def __enter__(self):
        return self

    def __exit__(self, typ, value, traceback):
        try:
            if typ is None:
                self.connection.commit()
            else:
                self.connection.rollback()
        finally:
            self.connection.close()

    def execute(self, query, params=()):
        if query == 'BEGIN IMMEDIATE':
            return self.connection.execute('SELECT pg_advisory_xact_lock(492031)')
        query = re.sub(r'(?<![\w"])end(?![\w"])', '"end"', query, flags=re.IGNORECASE)
        return self.connection.execute(query.replace('?', '%s'), params)

    def executemany(self, query, params):
        with self.connection.cursor() as cursor:
            cursor.executemany(query.replace('?', '%s'), params)


def connect():
    if DATABASE_URL:
        return PostgresConnection(DATABASE_URL)
    if os.environ.get('VERCEL'):
        raise RuntimeError('A Postgres DATABASE_URL or POSTGRES_URL must be configured')
    db = sqlite3.connect(DB, timeout=10)
    db.row_factory = sqlite3.Row
    db.execute('PRAGMA foreign_keys=ON')
    return db


def initialize():
    with connect() as db:
        if DATABASE_URL:
            db.execute('BEGIN IMMEDIATE')
            db.execute('CREATE TABLE IF NOT EXISTS rooms (code TEXT PRIMARY KEY, name TEXT NOT NULL, passcode_hash TEXT)')
            db.execute("CREATE TABLE IF NOT EXISTS machines (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type TEXT NOT NULL, name TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'free', owner TEXT, \"end\" DOUBLE PRECISION, room TEXT NOT NULL REFERENCES rooms(code), next_reminder DOUBLE PRECISION)")
            db.execute('CREATE TABLE IF NOT EXISTS queue (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, machine_id INTEGER NOT NULL REFERENCES machines(id), client TEXT NOT NULL, UNIQUE(machine_id,client))')
            initialize_access(db)
            return
        db.executescript('''CREATE TABLE IF NOT EXISTS machines (id INTEGER PRIMARY KEY, type TEXT NOT NULL, name TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'free', owner TEXT, end REAL);
        CREATE TABLE IF NOT EXISTS queue (id INTEGER PRIMARY KEY AUTOINCREMENT, machine_id INTEGER NOT NULL REFERENCES machines(id), client TEXT NOT NULL, UNIQUE(machine_id,client));
        CREATE TABLE IF NOT EXISTS rooms (code TEXT PRIMARY KEY, name TEXT NOT NULL);''')
        db.execute("INSERT OR IGNORE INTO rooms(code,name) VALUES('MAPLE1','Maple House')")
        if 'passcode_hash' not in [row['name'] for row in db.execute('PRAGMA table_info(rooms)')]:
            db.execute('ALTER TABLE rooms ADD COLUMN passcode_hash TEXT')
        if 'room' not in [row['name'] for row in db.execute('PRAGMA table_info(machines)')]:
            db.execute("ALTER TABLE machines ADD COLUMN room TEXT NOT NULL DEFAULT 'MAPLE1'")
        if 'next_reminder' not in [row['name'] for row in db.execute('PRAGMA table_info(machines)')]:
            db.execute('ALTER TABLE machines ADD COLUMN next_reminder REAL')
        if not db.execute('SELECT 1 FROM machines LIMIT 1').fetchone():
            db.executemany('INSERT INTO machines(id,type,name) VALUES(?,?,?)', [(i, 'washer' if i <= 3 else 'dryer', ('Washer' if i <= 3 else 'Dryer') + f' {((i-1)%3)+1:02}') for i in range(1,7)])

        initialize_access(db)


def initialize_access(db):
    db.execute('CREATE TABLE IF NOT EXISTS left_rooms (room TEXT NOT NULL REFERENCES rooms(code), client TEXT NOT NULL, PRIMARY KEY(room,client))')
    db.execute('CREATE TABLE IF NOT EXISTS room_memberships (token_hash TEXT PRIMARY KEY, room TEXT NOT NULL REFERENCES rooms(code))')
    db.execute('CREATE TABLE IF NOT EXISTS push_devices (client TEXT PRIMARY KEY, subscription TEXT NOT NULL)')
    db.execute('CREATE TABLE IF NOT EXISTS push_keys (id INTEGER PRIMARY KEY, private_key TEXT NOT NULL, public_key TEXT NOT NULL)')


if not os.environ.get('VERCEL') or DATABASE_URL:
    initialize()

class Start(BaseModel):
    minutes: int = Field(ge=1, le=240, strict=True)

class RoomSetup(BaseModel):
    name: str = Field(min_length=1, max_length=60)
    washers: int = Field(ge=0, le=50, strict=True)
    dryers: int = Field(ge=0, le=50, strict=True)

    @field_validator('name', mode='before')
    @classmethod
    def clean_name(cls, value):
        if isinstance(value, str):
            value = value.strip()
            if any(unicodedata.category(char) in ('Cc', 'Cs') for char in value):
                raise HTTPException(422, 'Room names must use visible characters.')
        return value

class Passcode(BaseModel):
    passcode: str

    @field_validator('passcode')
    @classmethod
    def validate_passcode(cls, value):
        if not 6 <= len(value) <= 128 or not value.strip():
            raise HTTPException(422, 'Use a passcode with 6–128 characters and at least one non-space character.')
        if any(unicodedata.category(char) in ('Cc', 'Cs') for char in value):
            raise HTTPException(422, 'The passcode contains an unsupported character.')
        return value


