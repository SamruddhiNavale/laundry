async def reminder_worker():
    while True:
        try:
            await asyncio.to_thread(send_turn_alerts)
            await asyncio.to_thread(send_due_reminders)
            await asyncio.to_thread(record_worker_check)
        except Exception:
            logger.exception('Laundry reminder worker failed')
        await asyncio.sleep(15)


@asynccontextmanager
async def lifespan(app):
    worker = None if os.environ.get('VERCEL') else asyncio.create_task(reminder_worker())
    try:
        yield
    finally:
        if worker:
            worker.cancel()
            try:
                await worker
            except asyncio.CancelledError:
                pass


app = FastAPI(title='Loop Laundry API', lifespan=lifespan)


