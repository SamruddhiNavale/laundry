def send_due_reminders():
    now = time.time()
    with connect() as db:
        db.execute('BEGIN IMMEDIATE')
        transition(db)
        pending = list(db.execute("""
            SELECT m.id, m.name, m.room, m.owner, m.end, p.subscription
            FROM machines m JOIN push_devices p ON p.client=m.owner
            WHERE m.state='done' AND (m.next_reminder IS NULL OR m.next_reminder<=?)
              AND NOT EXISTS (SELECT 1 FROM left_rooms l WHERE l.room=m.room AND l.client=m.owner)
            ORDER BY m.next_reminder LIMIT 20
        """, (now,)))
        if not pending:
            return
        key = push_keys(db)['private_key']
        for m in pending:
            # Lease the reminder so overlapping workers do not both send it.
            db.execute('UPDATE machines SET next_reminder=? WHERE id=?', (now+180, m['id']))

    for m in pending:
        delay = 3600
        with connect() as db:
            current = db.execute("""
                SELECT 1 FROM machines m JOIN push_devices p ON m.owner=p.client
                WHERE m.id=? AND m.state='done' AND m.next_reminder=? AND p.subscription=?
                  AND NOT EXISTS (SELECT 1 FROM left_rooms l WHERE l.room=m.room AND l.client=m.owner)
            """, (m['id'], now+180, m['subscription'])).fetchone()
        if not current:
            continue
        try:
            with Session() as session:
                session.max_redirects = 0
                webpush(
                    subscription_info=json.loads(m['subscription']),
                    data=json.dumps({'room': m['room'], 'machine': m['id'], 'end': m['end'],
                                     'body': f"{m['name']} has finished. Have you removed your clothes?"}),
                    vapid_private_key=key,
                    vapid_claims={'sub': os.environ.get('LAUNDRY_PUSH_CONTACT', 'https://example.com')},
                    ttl=900, timeout=5, requests_session=session,
                )
        except WebPushException as exc:
            status = exc.response.status_code if exc.response is not None else None
            if status in (404, 410):
                with connect() as db:
                    db.execute('DELETE FROM push_devices WHERE client=? AND subscription=?',
                               (m['owner'], m['subscription']))
                delay = 0
            else:
                logger.warning('Push delivery failed for machine %s (status %s)', m['id'], status)
                delay = 60
        except Exception:
            logger.warning('Push delivery failed for machine %s', m['id'])
            delay = 60
        with connect() as db:
            db.execute("UPDATE machines SET next_reminder=? WHERE id=? AND state='done' "
                       "AND owner=? AND end=? AND next_reminder=?",
                       (time.time()+delay, m['id'], m['owner'], m['end'], now+180))


