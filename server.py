@app.get(SAVED_ROOM_PATH)
def restore_saved_rooms(request: Request):
    saved = []
    cookies = request.cookies
    with connect() as db:
        for key, token in cookies.items():
            if not key.startswith(ROOM_COOKIE_PREFIX) or not (0 < len(token) <= 128):
                continue
            code = key[len(ROOM_COOKIE_PREFIX):]
            room = db.execute("""
                SELECT r.code,r.name FROM room_memberships m JOIN rooms r ON r.code=m.room
                WHERE m.token_hash=? AND r.code=?
            """, (token_hash(token), code)).fetchone()
            if room:
                saved.append({**dict(room), 'token': token})
    return {'rooms': saved, 'last': cookies.get('loop_last_room'),
            'client': cookies.get('loop_device') if saved else None}


def resize(db, code, washers, dryers):
    for kind, count in [('washer', washers), ('dryer', dryers)]:
        rows = list(db.execute('SELECT * FROM machines WHERE room=? AND type=? ORDER BY id', (code, kind)))
        if len(rows) > count:
            remove = rows[count:]
            if any(m['state'] != 'free' or db.execute('SELECT 1 FROM queue WHERE machine_id=?', (m['id'],)).fetchone() for m in remove):
                raise HTTPException(409, 'Cannot remove machines that are in use or have a queue')
            db.executemany('DELETE FROM machines WHERE id=?', [(m['id'],) for m in remove])
        else:
            for n in range(len(rows)+1, count+1):
                db.execute('INSERT INTO machines(type,name,room) VALUES(?,?,?)', (kind, f'{kind.title()} {n:02}', code))

@app.post('/api/rooms')
def create_room(body: RoomSetup):
    name = body.name
    with connect() as db:
        db.execute('BEGIN IMMEDIATE')
        require_unique_room_name(db, name)
        code = secrets.token_hex(8).upper()
        while db.execute('SELECT 1 FROM rooms WHERE code=?', (code,)).fetchone(): code = secrets.token_hex(8).upper()
        db.execute('INSERT INTO rooms(code,name) VALUES(?,?)', (code,name))
        resize(db, code, body.washers, body.dryers)
        token = issue_room_token(db, code)
    return {'code': code, 'name': name, 'token': token}


def room_name_key(name):
    return unicodedata.normalize('NFC', name.strip().casefold())


def require_unique_room_name(db, name, current_room=None):
    name_key = room_name_key(name)
    for room in db.execute('SELECT code, name FROM rooms'):
        if room['code'] != current_room and room_name_key(room['name']) == name_key:
            raise HTTPException(409, 'A room with this name already exists. Choose a different room name.')


@app.put('/api/room')
def edit_room(body: RoomSetup, x_room_code: str = Header(default='MAPLE1'), x_room_token: Optional[str] = Header(default=None)):
    name = body.name
    with connect() as db:
        db.execute('BEGIN IMMEDIATE')
        room = get_room(db, x_room_code, x_room_token)
        if room_name_key(name) != room_name_key(room['name']):
            require_unique_room_name(db, name, room['code'])
        transition(db)
        resize(db, room['code'], body.washers, body.dryers)
        db.execute('UPDATE rooms SET name=? WHERE code=?', (name,room['code']))
    return {'ok': True}


def client_id(value: Optional[str]):
    if not value or len(value) > 128 or not all(c.isalnum() or c == '-' for c in value):
        raise HTTPException(400, 'Invalid client identifier')
    return value


def offer_queue_turns(db, now):
    db.execute("""
        INSERT INTO queue_turns(queue_id, deadline)
        SELECT MIN(q.id), ? FROM queue q JOIN machines m ON m.id=q.machine_id
        WHERE m.state='free' GROUP BY q.machine_id
        ON CONFLICT(queue_id) DO NOTHING
    """, (now + TURN_SECONDS,))


def transition(db):
    now = time.time()
    db.execute("UPDATE machines SET state='done', next_reminder=end WHERE state='busy' AND end <= ?", (now,))
    db.execute('DELETE FROM queue WHERE id IN (SELECT queue_id FROM queue_turns WHERE deadline<=?)', (now,))
    offer_queue_turns(db, now)


def record_worker_check():
    with connect() as db:
        now = time.time()
        workers = [1]
        if apns_configured():
            workers.append(2)
        if fcm_configured():
            workers.append(3)
        for worker in workers:
            db.execute('INSERT INTO reminder_worker_status(id,checked_at) VALUES(?,?) '
                       'ON CONFLICT(id) DO UPDATE SET checked_at=excluded.checked_at', (worker, now))


@app.get('/api/state')
def state(x_client_id: Optional[str] = Header(default=None), x_room_code: str = Header(default='MAPLE1'), x_room_token: Optional[str] = Header(default=None)):
    client = client_id(x_client_id)
    with connect() as db:
        if DATABASE_URL:
            db.execute('BEGIN IMMEDIATE')
        room = get_room(db, x_room_code, x_room_token)
        transition(db)
        machines = []
        for row in db.execute('SELECT * FROM machines WHERE room=? ORDER BY id', (room['code'],)):
            m = dict(row)
            m['mine'] = m.pop('owner') == client
            if not m['mine']:
                m.pop('next_reminder')
            queue = list(db.execute(
                'SELECT q.client,t.deadline FROM queue q LEFT JOIN queue_turns t ON t.queue_id=q.id '
                'WHERE q.machine_id=? ORDER BY q.id', (m['id'],)))
            m['queue_length'] = len(queue)
            m['queue_position'] = next((i for i, q in enumerate(queue, 1) if q['client'] == client), None)
            if m['queue_position'] == 1:
                m['turn_deadline'] = queue[0]['deadline']
            machines.append(m)
        device = db.execute('SELECT 1 FROM push_devices WHERE client=?', (client,)).fetchone()
        workers = {
            row['id'] for row in db.execute('SELECT id FROM reminder_worker_status WHERE checked_at>=?',
                                             (time.time() - WORKER_STATUS_TTL,))
        }
        return {'machines': machines, 'room': {'code': room['code'], 'name': room['name']},
                'push_registered': device is not None,
                'worker_active': 1 in workers, 'apns_active': 2 in workers, 'fcm_active': 3 in workers}


@app.post('/api/machines/{machine_id}/{action}')
def action(machine_id: int, action: str, payload: Optional[Start] = None, x_client_id: Optional[str] = Header(default=None), x_room_code: str = Header(default='MAPLE1'), x_room_token: Optional[str] = Header(default=None), x_cycle_end: Optional[float] = Header(default=None), x_queue_intent: Optional[Literal['join', 'leave']] = Header(default=None)):
    client = client_id(x_client_id)
    with connect() as db:
        db.execute('BEGIN IMMEDIATE')
        room = get_room(db, x_room_code, x_room_token)
        transition(db)
        row = db.execute('SELECT * FROM machines WHERE id=? AND room=?', (machine_id,room['code'])).fetchone()
        if not row: raise HTTPException(404, 'Machine not found')
        if x_cycle_end is not None and row['end'] != x_cycle_end:
            raise HTTPException(409, 'This cycle has changed. Refresh and try again.')
        if action == 'start':
            if payload is None: raise HTTPException(422, 'Cycle length is required')
            if row['state'] != 'free': raise HTTPException(409, 'Machine is not available')
            first = db.execute('SELECT client FROM queue WHERE machine_id=? ORDER BY id LIMIT 1', (machine_id,)).fetchone()
            if first and first['client'] != client: raise HTTPException(409, 'This machine is reserved for the first person in line')
            db.execute("UPDATE machines SET state='busy',owner=?,end=?,next_reminder=NULL WHERE id=?", (client,time.time()+payload.minutes*60,machine_id))
            db.execute('DELETE FROM queue WHERE machine_id=? AND client=?', (machine_id,client))
        elif action == 'finish':
            if row['state'] != 'busy' or row['owner'] != client: raise HTTPException(403, 'Only the person running this cycle can end it')
            db.execute("UPDATE machines SET state='done',next_reminder=? WHERE id=?", (time.time(),machine_id))
        elif action in ('clear', 'force-stop'):
            if action == 'clear' and (row['state'] != 'done' or row['owner'] != client):
                raise HTTPException(403, 'Only the person running this cycle can confirm pickup')
            if action == 'force-stop' and (row['state'] != 'done' or x_cycle_end is None):
                raise HTTPException(409, 'This completed cycle is no longer available to release')
            db.execute("UPDATE machines SET state='free',owner=NULL,end=NULL,next_reminder=NULL WHERE id=?", (machine_id,))
            offer_queue_turns(db, time.time())
        elif action == 'remind':
            if row['state'] != 'done' or row['owner'] != client: raise HTTPException(403, 'Only the cycle owner can receive this reminder')
            if db.execute('SELECT 1 FROM push_devices WHERE client=?', (client,)).fetchone():
                raise HTTPException(409, 'The notification worker handles this reminder')
            if row['next_reminder'] is not None and row['next_reminder'] > time.time(): raise HTTPException(409, 'Reminder is not due')
            db.execute('UPDATE machines SET next_reminder=? WHERE id=?', (time.time()+3600,machine_id))
        elif action == 'still-there':
            if row['state'] != 'done' or row['owner'] != client: raise HTTPException(403, 'Only the cycle owner can respond')
            db.execute('UPDATE machines SET next_reminder=? WHERE id=?', (time.time()+3600,machine_id))
        elif action == 'queue':
            existing = db.execute('SELECT id FROM queue WHERE machine_id=? AND client=?', (machine_id,client)).fetchone()
            if existing:
                if x_queue_intent != 'join':
                    db.execute('DELETE FROM queue WHERE id=?', (existing['id'],))
                    offer_queue_turns(db, time.time())
            elif x_queue_intent == 'leave':
                return {'ok': True}
            elif row['state'] == 'free' and not db.execute('SELECT 1 FROM queue WHERE machine_id=?', (machine_id,)).fetchone(): raise HTTPException(409, 'This machine is available')
            elif row['owner'] == client: raise HTTPException(409, 'You are using this machine')
            else: db.execute('INSERT INTO queue(machine_id,client) VALUES(?,?)', (machine_id,client))
        else: raise HTTPException(404, 'Unknown action')
    return {'ok': True}

def push_keys(db):
    keys = db.execute('SELECT * FROM push_keys WHERE id=1').fetchone()
    if keys:
        return keys
    key = ec.generate_private_key(ec.SECP256R1())
    private = key.private_bytes(serialization.Encoding.DER, serialization.PrivateFormat.PKCS8,
                                serialization.NoEncryption())
    public = key.public_key().public_bytes(serialization.Encoding.X962,
                                           serialization.PublicFormat.UncompressedPoint)
    db.execute('INSERT INTO push_keys(id,private_key,public_key) VALUES(1,?,?) ON CONFLICT DO NOTHING',
               tuple(base64.urlsafe_b64encode(value).decode().rstrip('=') for value in (private, public)))
    return db.execute('SELECT * FROM push_keys WHERE id=1').fetchone()


