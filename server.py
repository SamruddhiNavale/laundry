class PostgresConnection:
    """Small compatibility layer for the app's parameterized SQLite queries."""
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row
        self.connection = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)

    def __enter__(self):
        return self

    def __exit__(self, typ, value, traceback):
        try:
            if typ is None:
                self.connection.commit()
            else:
                self.connection.rollback()
        finally:
            self.connection.close()

    def execute(self, query, params=()):
        if query == 'BEGIN IMMEDIATE':
            return self.connection.execute('SELECT pg_advisory_xact_lock(492031)')
        query = re.sub(r'(?<![\w"])end(?![\w"])', '"end"', query, flags=re.IGNORECASE)
        return self.connection.execute(query.replace('?', '%s'), params)

    def executemany(self, query, params):
        with self.connection.cursor() as cursor:
            cursor.executemany(query.replace('?', '%s'), params)


def connect():
    if DATABASE_URL:
        return PostgresConnection(DATABASE_URL)
    if os.environ.get('VERCEL'):
        raise RuntimeError('A Postgres DATABASE_URL or POSTGRES_URL must be configured')
    db = sqlite3.connect(DB, timeout=10)
    db.row_factory = sqlite3.Row
    db.execute('PRAGMA foreign_keys=ON')
    return db


def initialize():
    with connect() as db:
        if DATABASE_URL:
            db.execute('BEGIN IMMEDIATE')
            db.execute('CREATE TABLE IF NOT EXISTS rooms (code TEXT PRIMARY KEY, name TEXT NOT NULL)')
            db.execute("CREATE TABLE IF NOT EXISTS machines (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type TEXT NOT NULL, name TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'free', owner TEXT, \"end\" DOUBLE PRECISION, room TEXT NOT NULL REFERENCES rooms(code), next_reminder DOUBLE PRECISION)")
            db.execute('CREATE TABLE IF NOT EXISTS queue (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, machine_id INTEGER NOT NULL REFERENCES machines(id), client TEXT NOT NULL, UNIQUE(machine_id,client))')
            initialize_access(db)
            return
        db.executescript('''CREATE TABLE IF NOT EXISTS machines (id INTEGER PRIMARY KEY, type TEXT NOT NULL, name TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'free', owner TEXT, end REAL);
        CREATE TABLE IF NOT EXISTS queue (id INTEGER PRIMARY KEY AUTOINCREMENT, machine_id INTEGER NOT NULL REFERENCES machines(id), client TEXT NOT NULL, UNIQUE(machine_id,client));
        CREATE TABLE IF NOT EXISTS rooms (code TEXT PRIMARY KEY, name TEXT NOT NULL);''')
        db.execute("INSERT OR IGNORE INTO rooms(code,name) VALUES('MAPLE1','Maple House')")
        if 'room' not in [row['name'] for row in db.execute('PRAGMA table_info(machines)')]:
            db.execute("ALTER TABLE machines ADD COLUMN room TEXT NOT NULL DEFAULT 'MAPLE1'")
        if 'next_reminder' not in [row['name'] for row in db.execute('PRAGMA table_info(machines)')]:
            db.execute('ALTER TABLE machines ADD COLUMN next_reminder REAL')
        if not db.execute('SELECT 1 FROM machines LIMIT 1').fetchone():
            db.executemany('INSERT INTO machines(id,type,name) VALUES(?,?,?)', [(i, 'washer' if i <= 3 else 'dryer', ('Washer' if i <= 3 else 'Dryer') + f' {((i-1)%3)+1:02}') for i in range(1,7)])

        initialize_access(db)


